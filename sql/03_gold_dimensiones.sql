-- ---------------------------------------------------------------- dim_inversor (SCD tipo 2)
CREATE TABLE IF NOT EXISTS gold.dim_inversor (
    inversor_sk           integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 0 = desconocido
    inversor_id           smallint NOT NULL CHECK (inversor_id IN (0, 1, 2)),
    nombre                text     NOT NULL,             -- SCD tipo 1
    cargas                text,
    firmware_build        text,
    version_lib           text,
    prioridad_salida      smallint,
    prioridad_carga       smallint,
    potencia_max_red_w    integer,
    capacidad_bateria_ah  integer,
    capacidad_bateria_kwh numeric(6,2) GENERATED ALWAYS AS (capacidad_bateria_ah * 48 / 1000.0) STORED,
    soc_alarma_pct        smallint,
    soc_corte_pct         smallint,
    vigente_desde         date     NOT NULL,
    vigente_hasta         date     NOT NULL DEFAULT DATE '9999-12-31',
    es_vigente            boolean  GENERATED ALWAYS AS (vigente_hasta = DATE '9999-12-31') STORED,
    UNIQUE (inversor_id, vigente_desde),
    CHECK (vigente_hasta >= vigente_desde)
);
COMMENT ON TABLE gold.dim_inversor IS 'SCD tipo 2: una fila por versión de configuración (moda diaria estable >= 3 días). La llena el ETL.';

