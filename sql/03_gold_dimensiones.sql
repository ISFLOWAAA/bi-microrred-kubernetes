-- Tarifa vigente en una fecha. Si la fecha es anterior a la primera vigencia
-- se usa la tarifa publicada más antigua (supuesto declarado: la tarifa de
-- abril de 2026 se aplica a todo el histórico, "como si" fuera Medellín).
CREATE OR REPLACE FUNCTION gold.tarifa_cop_kwh(p_fecha date,
                                               p_tipo text DEFAULT 'Oficial',
                                               p_franja text DEFAULT 'Monomia')
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT valor_cop_kwh
      FROM gold.dim_tarifa
     WHERE tipo_tarifa = p_tipo AND franja = p_franja
       AND p_fecha <= vigente_hasta
     ORDER BY (vigente_desde <= p_fecha) DESC, abs(p_fecha - vigente_desde)
     LIMIT 1;
$$;
