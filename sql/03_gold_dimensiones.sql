-- Versión vigente de un inversor en una fecha (la usan el ETL y el simulador).
CREATE OR REPLACE FUNCTION gold.inversor_sk_vigente(p_inversor_id smallint, p_fecha date)
RETURNS integer LANGUAGE sql STABLE AS $$
    SELECT coalesce(
        (SELECT inversor_sk FROM gold.dim_inversor
          WHERE inversor_id = p_inversor_id
            AND p_fecha BETWEEN vigente_desde AND vigente_hasta
          ORDER BY vigente_desde DESC LIMIT 1),
        0);
$$;

-- ---------------------------------------------------------------- dim_estado_operativo (junk)
-- Todas las combinaciones se enumeran por adelantado con una fórmula fija,
-- así el ETL y el simulador calculan la llave sin consultar la tabla:
--   estado_key = idx(modo)*12 + idx(carga)*3 + idx(régimen)
--   idx(modo):   sin dato=0, 0=1, 1=2, 2=3      (status.outstatus)
--   idx(carga):  sin dato=0, 0=1, 1=2, otro=3   (status.chgstatus)
--   idx(régimen): Sin dato=0, Conectado=1, Isla=2
-- La combinación "todo sin dato" da 0 = miembro desconocido.
CREATE TABLE IF NOT EXISTS gold.dim_estado_operativo (
    estado_key       smallint PRIMARY KEY CHECK (estado_key BETWEEN 0 AND 47),
    modo_salida_cod  smallint NOT NULL,                  -- -1 = sin dato, 0, 1, 2
    modo_salida      text     NOT NULL,
    estado_carga_cod smallint NOT NULL,                  -- -1 = sin dato, 0, 1, 9 = otro
    estado_carga     text     NOT NULL,
    regimen_red      text     NOT NULL CHECK (regimen_red IN ('Conectado', 'Isla', 'Sin dato')),
    UNIQUE (modo_salida_cod, estado_carga_cod, regimen_red)
);

INSERT INTO gold.dim_estado_operativo
SELECT mo.i * 12 + ca.i * 3 + re.i,
       mo.cod, mo.nombre, ca.cod, ca.nombre, re.nombre
FROM (VALUES (0, -1, 'Sin dato'), (1, 0, 'Apagado / espera'),
             (2, 1, 'Modo red'), (3, 2, 'Modo inversor')) AS mo(i, cod, nombre),
     (VALUES (0, -1, 'Sin dato'), (1, 0, 'No carga'),
             (2, 1, 'Cargando'), (3, 9, 'Otro')) AS ca(i, cod, nombre),
     (VALUES (0, 'Sin dato'), (1, 'Conectado'), (2, 'Isla')) AS re(i, nombre)
ON CONFLICT (estado_key) DO NOTHING;

CREATE OR REPLACE FUNCTION gold.estado_key(p_modo smallint, p_carga smallint, p_regimen text)
RETURNS smallint LANGUAGE sql IMMUTABLE AS $$
    SELECT ( (CASE p_modo  WHEN 0 THEN 1 WHEN 1 THEN 2 WHEN 2 THEN 3 ELSE 0 END) * 12
           + (CASE WHEN p_carga IS NULL THEN 0 WHEN p_carga = 0 THEN 1 WHEN p_carga = 1 THEN 2 ELSE 3 END) * 3
           + (CASE p_regimen WHEN 'Conectado' THEN 1 WHEN 'Isla' THEN 2 ELSE 0 END) )::smallint;
$$;

