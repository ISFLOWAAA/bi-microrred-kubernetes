SELECT m,
       m / 60,
       m % 60,
       to_char(m / 60, 'FM00') || ':' || to_char(m % 60, 'FM00'),
       CASE WHEN m / 60 < 6  THEN 'Madrugada'
            WHEN m / 60 < 12 THEN 'Mañana'
