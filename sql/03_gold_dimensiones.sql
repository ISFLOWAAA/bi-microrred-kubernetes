-- ---------------------------------------------------------------- dim_fecha
-- Un día local. Cubre el histórico (2025-07 → 2026-07) y deja margen hasta
-- 2027-12-31 para las filas que inserte el simulador (Fase 8).
CREATE TABLE IF NOT EXISTS gold.dim_fecha (
    fecha_key         integer  PRIMARY KEY,               -- YYYYMMDD; 0 = desconocido
    fecha             date     NOT NULL UNIQUE,
    anio              smallint NOT NULL,
    trimestre         smallint NOT NULL,
    mes               smallint NOT NULL,
    dia_mes           smallint NOT NULL,
    nombre_mes        text     NOT NULL,
    nombre_dia        text     NOT NULL,
    anio_mes          text     NOT NULL,                  -- 'YYYY-MM'
    semana_iso        smallint NOT NULL,
    dia_semana        smallint NOT NULL,                  -- ISO: lunes = 1
    es_fin_de_semana  boolean  NOT NULL,
    tipo_dia          text     NOT NULL CHECK (tipo_dia IN ('Laboral', 'Fin de semana', 'Festivo', 'Sin dato')),
    periodo_academico text     NOT NULL DEFAULT 'Sin dato'  -- lo completa el ETL desde context
);
COMMENT ON TABLE gold.dim_fecha IS 'Grano: un día local (Asia/Shanghai). tipo_dia y periodo_academico se ajustan en el ETL con context.';

